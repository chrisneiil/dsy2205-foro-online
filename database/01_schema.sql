-- Esquema del foro. Ejecutar conectado al usuario dueño de las tablas.
CREATE TABLE FORUM_USERS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(40) NOT NULL UNIQUE,
    EMAIL VARCHAR2(120) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR2(100) NOT NULL,
    DISPLAY_NAME VARCHAR2(80) NOT NULL,
    USER_ROLE VARCHAR2(12) DEFAULT 'USER' NOT NULL,
    ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT CK_FORUM_USERS_ROLE CHECK (USER_ROLE IN ('USER', 'ADMIN')),
    CONSTRAINT CK_FORUM_USERS_ACTIVE CHECK (ACTIVE IN (0, 1))
);

CREATE TABLE FORUM_CATEGORIES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(60) NOT NULL UNIQUE,
    DESCRIPTION VARCHAR2(240) NOT NULL
);

CREATE TABLE FORUM_TOPICS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE VARCHAR2(160) NOT NULL,
    BODY CLOB NOT NULL,
    STATUS VARCHAR2(12) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    AUTHOR_ID NUMBER NOT NULL,
    CATEGORY_ID NUMBER NOT NULL,
    CONSTRAINT FK_TOPIC_AUTHOR FOREIGN KEY (AUTHOR_ID) REFERENCES FORUM_USERS(ID),
    CONSTRAINT FK_TOPIC_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES FORUM_CATEGORIES(ID),
    CONSTRAINT CK_TOPIC_STATUS CHECK (STATUS IN ('ACTIVE', 'HIDDEN'))
);

CREATE TABLE FORUM_COMMENTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BODY VARCHAR2(1000) NOT NULL,
    STATUS VARCHAR2(12) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    TOPIC_ID NUMBER NOT NULL,
    AUTHOR_ID NUMBER NOT NULL,
    CONSTRAINT FK_COMMENT_TOPIC FOREIGN KEY (TOPIC_ID) REFERENCES FORUM_TOPICS(ID),
    CONSTRAINT FK_COMMENT_AUTHOR FOREIGN KEY (AUTHOR_ID) REFERENCES FORUM_USERS(ID),
    CONSTRAINT CK_COMMENT_STATUS CHECK (STATUS IN ('ACTIVE', 'HIDDEN'))
);

CREATE INDEX IX_TOPICS_CATEGORY ON FORUM_TOPICS(CATEGORY_ID);
CREATE INDEX IX_TOPICS_AUTHOR ON FORUM_TOPICS(AUTHOR_ID);
CREATE INDEX IX_COMMENTS_TOPIC ON FORUM_COMMENTS(TOPIC_ID);
