-- Ejecuta estas consultas durante la grabación para mostrar persistencia Oracle.
SELECT ID, USERNAME, EMAIL, DISPLAY_NAME, USER_ROLE, ACTIVE, CREATED_AT FROM FORUM_USERS ORDER BY ID;
SELECT ID, NAME, DESCRIPTION FROM FORUM_CATEGORIES ORDER BY ID;
SELECT T.ID, T.TITLE, T.STATUS, C.NAME AS CATEGORY, U.USERNAME AS AUTHOR, T.CREATED_AT
  FROM FORUM_TOPICS T JOIN FORUM_CATEGORIES C ON C.ID=T.CATEGORY_ID JOIN FORUM_USERS U ON U.ID=T.AUTHOR_ID ORDER BY T.ID;
SELECT C.ID, C.BODY, C.STATUS, T.TITLE AS TOPIC, U.USERNAME AS AUTHOR, C.CREATED_AT
  FROM FORUM_COMMENTS C JOIN FORUM_TOPICS T ON T.ID=C.TOPIC_ID JOIN FORUM_USERS U ON U.ID=C.AUTHOR_ID ORDER BY C.ID;
SELECT C.NAME, COUNT(DISTINCT T.ID) AS TOPICS, COUNT(DISTINCT CM.ID) AS COMMENTS
  FROM FORUM_CATEGORIES C LEFT JOIN FORUM_TOPICS T ON T.CATEGORY_ID=C.ID
  LEFT JOIN FORUM_COMMENTS CM ON CM.TOPIC_ID=T.ID GROUP BY C.NAME ORDER BY C.NAME;

